import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {renderDocument} from '../server/runtime/document.mjs';
const chinese={id:7,slug:'shared-post',status:'published',title:'中文文章',summary:'中文简介',content:'# 中文标题\n\n中文正文',tags:'[]',author_name:'mooncci',published_at:'2026-01-01',content_locale:'zh-CN',available_locales:['zh-CN','en']};
const english={...chinese,title:'English article',summary:'English summary',content:'# English heading\n\nEnglish body.',content_locale:'en'};
async function load(path){
 const url=new URL(path,'http://local'),en=url.searchParams.get('locale')==='en';
 if(url.pathname==='/settings/site')return {brand:{site_title:'mooncci'},hero:{},footer:{}};
 if(url.pathname==='/publishing/config')return {enabled:true};
 if(url.pathname==='/subscriptions/status')return {available:false};
 if(url.pathname==='/posts/shared-post')return en?english:chinese;
 if(url.pathname.endsWith('/discovery'))return {previous:null,next:null,related:[]};
 if(url.pathname==='/settings/blog-pages')return {about:null,links:[]};
 if(url.pathname==='/now')return {content:''};
 if(url.pathname==='/posts')return {items:[en?english:chinese],total:1,page:1,pageSize:12};
 return {items:[],total:0,page:1,pageSize:12};
}
const [zh,en]=await Promise.all([renderDocument('/article/shared-post',load),renderDocument('/en/article/shared-post',load)]);
const zhDom=JSDOM.fragment(zh.html),enDom=JSDOM.fragment(en.html);
assert.match(zhDom.textContent,/中文正文/);assert.doesNotMatch(zhDom.textContent,/English body/);
assert.match(enDom.textContent,/English body/);assert.doesNotMatch(enDom.textContent,/中文正文/);
assert.equal(enDom.querySelectorAll('h1').length,1);
assert.equal(en.data.locale,'en');assert.equal(zh.data.locale,'zh-CN');
assert.ok(en.data.resources['/posts/shared-post?locale=en']);assert.ok(zh.data.resources['/posts/shared-post']);
assert.equal(enDom.querySelector('h1')?.textContent,'English article');
assert.equal(enDom.querySelector('.language-trigger')?.getAttribute('aria-label'),'Interface language');
assert.equal(enDom.querySelector('.language-trigger')?.getAttribute('aria-haspopup'),'menu');
assert.equal(enDom.querySelector('.language-trigger')?.getAttribute('aria-expanded'),'false');
assert.equal(enDom.querySelector('a[hreflang="en"]')?.getAttribute('href'),'/en/article/shared-post');
assert.equal(enDom.querySelector('a[hreflang="en"]')?.getAttribute('aria-current'),'page');
assert.equal(enDom.querySelector('a[hreflang="zh-CN"]')?.getAttribute('href'),'/article/shared-post');
assert.equal(zhDom.querySelector('a[hreflang="zh-CN"]')?.getAttribute('aria-current'),'page');
assert.doesNotMatch(zh.html,/m_[a-f0-9]{10}/,'Chinese SSR must seed the source catalog before rendering');
assert.doesNotMatch(en.html,/m_[a-f0-9]{10}/,'English SSR must resolve compact catalog keys');
const missing=await renderDocument('/en/article/missing',load,404);
assert.doesNotMatch(missing.html,/English body|中文正文/);
const list=await renderDocument('/en/articles',load);
assert.match(list.html,/href="\/en\/article\/shared-post"/);
const listDom=JSDOM.fragment(list.html);
assert.equal(listDom.querySelector('.desktop-nav a')?.getAttribute('href'),'/en/articles');
const fallback=await renderDocument('/en/articles',async path=>new URL(path,'http://local').pathname==='/posts'?{items:[{...chinese,available_locales:['zh-CN']}],total:1,page:1,pageSize:12}:load(path));
const fallbackDom=JSDOM.fragment(fallback.html);
assert.equal(fallbackDom.querySelector('.blog-card')?.closest('a')?.getAttribute('href'),'/article/shared-post');
assert.equal(fallbackDom.querySelector('.blog-card h3')?.getAttribute('lang'),'zh-CN');
console.log('Bilingual SSR passed: English and Chinese bodies without JS, same post identity, isolated locale resource keys, strict missing document, localized list links.');
