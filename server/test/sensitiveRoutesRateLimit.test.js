const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');

test('sensitive routes bound requests even when mounted without the main application', async t => {
  const auth = require('../src/middleware/auth');
  const original = { authRequired: auth.authRequired, adminOnly: auth.adminOnly, ownerOnly: auth.ownerOnly, editorOrAdmin: auth.editorOrAdmin };
  const allow = (_req, _res, next) => next();
  Object.assign(auth, { authRequired: allow, adminOnly: allow, ownerOnly: allow, editorOrAdmin: allow });
  const db = require('../src/db'), query = db.query;
  db.query = async sql => sql.startsWith('SELECT COUNT(') ? [[{ total: 0 }]] : [[]];
  const workflow = require('../src/services/articleWorkflow'), enabled = workflow.enabled, change = workflow.change;
  workflow.enabled = () => true; workflow.change = async () => ({});
  const app = express(); app.use(express.json()); app.use((req, _res, next) => { req.user = { id: 1, role: 'owner' }; next(); });
  app.use('/tokens', require('../src/routes/serviceTokens'));
  app.use('/translations', require('../src/routes/contentTranslations').createContentTranslations({ db, authRequired: allow, adminOnly: allow }));
  app.use('/publishing', require('../src/routes/publishing'));
  app.use('/posts', require('../src/routes/posts'));
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); db.query = query; workflow.enabled = enabled; workflow.change = change; Object.assign(auth, original); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (url, method = 'GET') => fetch(base + url, { method, headers: { 'content-type': 'application/json' }, ...(method === 'GET' ? {} : { body: '{}' }) });
  assert.equal((await request('/tokens')).status, 200);
  assert.equal((await request('/tokens', 'POST')).status, 400);
  assert.equal((await request('/tokens/0/revoke', 'POST')).status, 400);
  for (let i = 0; i < 57; i++) assert.equal((await request('/tokens')).status, 200);
  assert.equal((await request('/tokens')).status, 429);
  assert.equal((await request('/translations/invalid/1')).status, 400);
  assert.equal((await request('/translations/invalid/1', 'PUT')).status, 400);
  for (let i = 0; i < 118; i++) assert.equal((await request('/translations/invalid/1')).status, 400);
  assert.equal((await request('/translations/invalid/1', 'PUT')).status, 429);
  assert.equal((await request('/publishing/queue')).status, 200);
  assert.equal((await request('/publishing/1/submit', 'POST')).status, 200);
  for (let i = 0; i < 118; i++) assert.equal((await request('/publishing/queue')).status, 200);
  assert.equal((await request('/publishing/1/submit', 'POST')).status, 429);
  assert.equal((await request('/publishing/config')).status, 200, 'public config has a separate budget');
  assert.equal((await request('/posts/meta/categories')).status, 200);
  assert.equal((await request('/posts/meta/tags')).status, 200);
  for (let i = 0; i < 198; i++) assert.equal((await request('/posts')).status, 200);
  assert.equal((await request('/posts/meta/categories')).status, 429);
  assert.equal((await request('/posts/meta/tags')).status, 429);
  assert.equal((await request('/posts')).status, 429);
  assert.equal((await request('/posts', 'POST')).status, 400);
  assert.equal((await request('/posts/1', 'PUT')).status, 404);
  for (let i = 0; i < 198; i++) assert.equal((await request('/posts', 'POST')).status, 400);
  assert.equal((await request('/posts/1', 'PUT')).status, 429);
});
