const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

test('daily question lifecycle, dedupe, cutoff, moderation and privacy', { skip: process.env.DAILY_QUESTION_INTEGRATION !== 'true' }, async t => {
  const mysql = require('mysql2/promise'), express = require('express');
  const name = `mooncci_qa_daily_${process.pid}`;
  const setup = await mysql.createConnection({ host:'127.0.0.1', port:Number(process.env.TEST_DB_PORT || 33079), user:'root', password:'', multipleStatements:true });
  await setup.query(`CREATE DATABASE \`${name}\` CHARACTER SET utf8mb4`);
  await setup.query(`USE \`${name}\``);
  await setup.query('CREATE TABLE banned_words (id INT AUTO_INCREMENT PRIMARY KEY, word VARCHAR(100) NOT NULL)');
  await setup.query("INSERT INTO banned_words(word) VALUES ('禁词')");
  await setup.query(fs.readFileSync(path.join(__dirname, '../database/migrations/202611120003_daily_questions.sql'), 'utf8'));
  await setup.query(fs.readFileSync(path.join(__dirname, '../database/migrations/202611120003_daily_questions.sql'), 'utf8'));
  const db = mysql.createPool({ host:'127.0.0.1', port:Number(process.env.TEST_DB_PORT || 33079), user:'root', password:'', database:name, connectionLimit:6 });
  const auth = require('../src/middleware/auth');
  t.mock.method(auth, 'authRequired', (req,res,next) => { if (!req.get('x-role')) return res.sendStatus(401); req.user = {id:1, role:req.get('x-role')}; next(); });
  t.mock.method(auth, 'adminOnly', (req,res,next) => ['owner','admin'].includes(req.user.role) ? next() : res.sendStatus(403));
  const { createDailyRouters } = require('../src/routes/dailyQuestions');
  let now = Date.parse('2026-11-12T01:00:00Z');
  let notices = 0;
  const endpoints = createDailyRouters({ db, now:() => now, secret:()=> 'integration-test-secret', notify: async () => { notices++; }, getUser:async req => req.get('x-user') ? {id:Number(req.get('x-user')),status:'active'} : null });
  const app = express(); app.use(express.json()); app.use('/api/daily-question', endpoints.router); app.use('/api/admin/daily-questions', endpoints.admin);
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await db.end(); await setup.query(`DROP DATABASE \`${name}\``); await setup.end(); await require('../src/db').end(); });
  const request = (url, { method='GET', body, cookie, role, user } = {}) => fetch(`http://127.0.0.1:${server.address().port}/api${url}`, { method, headers: { 'Content-Type':'application/json', ...(cookie ? {Cookie:cookie} : {}), ...(role ? {'x-role':role} : {}), ...(user ? {'x-user':String(user)} : {}) }, ...(body ? {body:JSON.stringify(body)} : {}) });
  const admin = '/admin/daily-questions/2026-11-12';
  const draft = {text:'今天喝什么？', choices:['咖啡','茶']};
  assert.equal((await request(admin,{method:'PUT',body:draft})).status,401);
  assert.equal((await request(admin,{method:'PUT',role:'user',body:draft})).status,403);
  assert.equal((await request(admin,{method:'PUT',role:'owner',body:{...draft,text:'字'.repeat(41)}})).status,400);
  assert.equal((await request(admin,{method:'PUT',role:'owner',body:draft})).status,200);
  now = Date.parse('2026-11-12T02:00:00Z');
  assert.deepEqual(await (await request('/daily-question')).json(),{active:false},'draft stays private after 10:00');
  now = Date.parse('2026-11-12T00:59:59Z');
  assert.equal((await request('/daily-question/answers',{method:'POST',body:{choiceIndex:0}})).status,403,'before 09:00 is closed');
  now = Date.parse('2026-11-12T01:00:00Z');
  assert.deepEqual(await (await request('/daily-question')).json(),{active:false});
  assert.equal((await request('/daily-question/answers',{method:'POST',body:{choiceIndex:0}})).status,403);
  assert.equal((await request(admin+'/publish',{method:'POST',role:'owner'})).status,200);
  assert.deepEqual(await (await request('/daily-question')).json(),{active:false},'before 10:00 question is not advertised');
  const first = await request('/daily-question/answers',{method:'POST',body:{choiceIndex:0}});
  assert.equal(first.status,200,'09:00 accepts direct submissions');
  const cookie = first.headers.get('set-cookie').split(';')[0];
  assert.equal((await request('/daily-question/answers',{method:'POST',cookie,body:{choiceIndex:0}})).status,409);
  now = Date.parse('2026-11-12T02:00:00Z');
  const active = await (await request('/daily-question',{cookie})).json();
  assert.equal(active.active,true); assert.equal(active.answered,true);
  assert.equal((await request('/daily-question/preview')).status,403);
  assert.deepEqual((await (await request('/daily-question/preview',{cookie})).json()).preview.counts,[1,0]);
  now = Date.parse('2026-11-12T14:00:00Z');
  assert.equal((await request(admin+'/generate',{method:'POST',role:'admin'})).status,200);
  assert.equal((await (await request('/daily-question/summary')).json()).summary,null);
  assert.equal((await request(admin+'/review',{method:'POST',role:'admin',body:{decision:'approve'}})).status,200);
  const concurrent = await Promise.all(Array.from({length:5}, () => request('/daily-question/answers',{method:'POST',user:2,body:{choiceIndex:1}})));
  assert.deepEqual(concurrent.map(response => response.status).sort(),[200,409,409,409,409]);
  const adminView = await (await request('/admin/daily-questions?date=2026-11-12',{role:'owner'})).json();
  assert.equal(adminView.question.summary_status,'none','late answers invalidate approval');
  assert.equal(adminView.items[0].question_date,'2026-11-12');
  assert.equal(adminView.items[0].answer_count,2);
  now = Date.parse('2026-11-12T15:00:00Z');
  assert.equal((await request('/daily-question/answers',{method:'POST',user:3,body:{choiceIndex:1}})).status,403,'23:00 is closed');
  assert.equal((await request(admin+'/generate',{method:'POST',role:'admin'})).status,200);
  now = Date.parse('2026-11-13T02:00:00Z');
  assert.equal((await (await request('/daily-question/summary')).json()).summary,null,'pending is private');
  assert.equal((await request(admin+'/review',{method:'POST',role:'owner',body:{decision:'reject'}})).status,200);
  assert.equal((await (await request('/daily-question/summary')).json()).summary,null,'rejected remains private');
  assert.equal((await request(admin+'/review',{method:'POST',role:'owner',body:{decision:'approve'}})).status,200);
  assert.match((await (await request('/daily-question/summary')).json()).summary,/回答人数：2/);
  const tomorrow = '/admin/daily-questions/2026-11-13';
  await request(tomorrow,{method:'PUT',role:'owner',body:{text:'今天有什么开心事？',choices:null}});
  await request(tomorrow+'/publish',{method:'POST',role:'owner'});
  for (const [user,text] of [[10,'今天喝咖啡非常开心'],[11,'朋友喝咖啡也很开心'],[12,'喝咖啡禁词'],[13,'喝咖啡 me@example.com']]) assert.equal((await request('/daily-question/answers',{method:'POST',user,body:{text}})).status,200);
  const preview = await (await request('/daily-question/preview',{user:10})).json();
  assert.deepEqual(preview.preview.words,[]);
  assert.equal(preview.preview.pendingReview,true);
  assert.equal(notices,4,'each open answer notifies the reviewer');
  assert.doesNotMatch(JSON.stringify(preview),/禁词|example|今天喝咖啡非常开心/);
  now = Date.parse('2026-11-13T14:00:00Z');
  const summary = (await (await request(tomorrow+'/generate',{method:'POST',role:'owner'})).json()).question.draft_summary;
  assert.match(summary,/咖啡（2）/); assert.doesNotMatch(summary,/禁词|example|今天喝咖啡非常开心/);
  assert.deepEqual((await (await request('/daily-question/preview',{user:10})).json()).preview.words,[],'pending summaries stay private');
  assert.equal((await request(tomorrow+'/review',{method:'POST',role:'owner',body:{decision:'approve'}})).status,200);
  assert.deepEqual((await (await request('/daily-question/preview',{user:10})).json()).preview.words,[{text:'咖啡',count:2},{text:'开心',count:2}]);
  const [[beforeDelete]] = await db.query('SELECT id FROM daily_questions WHERE question_date=?',['2026-11-13']);
  assert.equal((await request(tomorrow,{method:'DELETE'})).status,401);
  assert.equal((await request(tomorrow,{method:'DELETE',role:'user'})).status,403);
  assert.equal((await request(tomorrow,{method:'DELETE',role:'admin'})).status,200);
  const [[remaining]] = await db.query('SELECT COUNT(*) AS total FROM daily_answers WHERE question_id=?',[beforeDelete.id]);
  assert.equal(remaining.total,0,'deleting the question also removes answers');
  assert.equal((await request(tomorrow,{method:'DELETE',role:'admin'})).status,404);
});
